fn fail(message: impl std::fmt::Display) -> ! {
    eprintln!("sip-source: {message}");
    std::process::exit(1);
}

fn healthcheck() -> ! {
    let listen = config::var("SS_LISTEN").unwrap_or_else(|_| "0.0.0.0:8080".into());
    let port = listen.rsplit(':').next().unwrap_or("8080");
    let addr: SocketAddr = format!("127.0.0.1:{port}").parse().unwrap_or_else(|_| fail("bad SS_LISTEN"));
    let check = || -> std::io::Result<bool> {
        let mut s = TcpStream::connect_timeout(&addr, Duration::from_secs(3))?;
        s.set_read_timeout(Some(Duration::from_secs(3)))?;
        s.write_all(b"GET /readyz HTTP/1.0\r\n\r\n")?;
        let mut buf = [0u8; 16];
        s.read_exact(&mut buf)?;
        Ok(String::from_utf8_lossy(&buf).contains(" 200"))
    };
    std::process::exit(if check().unwrap_or(false) { 0 } else { 1 });
}

/// Prints the environment reference. The docs and `.env.example` are generated from this.
fn print_env(format: Option<&str>) -> ! {
    let default = |d: &str| if d.is_empty() { "–".to_string() } else { format!("`{d}`") };
    let boot_groups = ["Database", "Storage", "Network", "First start and secrets", "Logging"];
    match format {
        Some("--dotenv") => {
            println!("# Generated by `sip-source env --dotenv`. Only the three required values must be set.\n");
            println!("# Required");
            for (name, _, help, _, _) in config::BOOT_VARS.iter().filter(|v| v.3) {
                println!("# {help}\n{name}=");
            }
            for group in boot_groups {
                println!("\n# Optional: {group}");
                for (name, default, help, _, _) in config::BOOT_VARS.iter().filter(|v| !v.3 && v.4 == group) {
                    println!("# {help}\n#{name}={default}");
                }
            }
            let mut group = "";
            for d in config::DEFS {
                if d.group != group {
                    group = d.group;
                    println!("\n# Optional: {group}");
                }
                println!("# {}. {}\n#{}={}", d.label, d.help, config::env_name(d.key), d.default);
            }
        }
        _ => {
            println!("# Environment variables\n");
            println!("Generated by `sip-source env` from the code. Print the same list from the image with:\n");
            let tag = env!("CARGO_PKG_VERSION").rsplit_once('.').map_or(env!("CARGO_PKG_VERSION"), |(minor, _)| minor);
            println!("```bash\ndocker run --rm ntuxa76/sip-source:{tag} env\n```\n");
            println!("## How to set them\n");
            println!("- **Docker Compose:** add them under `environment:` of the `sip-source` service in `docker-compose.yml`, or put them in `.env` and reference them there.");
            println!("- **docker run:** pass each one with `-e NAME=value`.");
            println!("- **Secrets:** the passwords below also accept a `_FILE` variant, for example `SS_DB_PASSWORD_FILE=/run/secrets/db`, which reads the value from that file.\n");
            println!("Only `SS_DB_HOST`, `SS_DB_USER` and `SS_DB_PASSWORD` are required. Everything else has a working default.\n");
            println!("Storage isn't set here. Captured data goes to the built-in Local file storage under `SS_DATA_DIR` until you add a ClickHouse server under **Admin → Storage**.\n");
            println!("## Startup settings\n\nRead once when the container starts. Changing one means restarting the container.");
            for group in boot_groups {
                println!("\n### {group}\n\n| Variable | Default | Required | Description |\n|---|---|---|---|");
                for (name, d, help, required, _) in config::BOOT_VARS.iter().filter(|v| v.4 == group) {
                    println!("| `{name}` | {} | {} | {help}. |", default(d), if *required { "yes" } else { "no" });
                }
            }
            println!("\n## Application settings\n");
            println!("These can also be changed under **Admin → Settings**, where they are saved in MariaDB. A value set here takes priority over the saved one and shows as locked on that page. An invalid value stops the container at startup with a message naming the variable.");
            let mut group = "";
            for d in config::DEFS {
                if d.group != group {
                    group = d.group;
                    println!("\n### {group}\n\n| Variable | Default | Applies | Description |\n|---|---|---|---|");
                }
                let kind = match d.kind {
                    config::Kind::Int(lo, hi) => format!(" Whole number, {lo} to {hi}."),
                    config::Kind::Bool => " `true` or `false`.".to_string(),
                    config::Kind::Choice(opts) => format!(" One of: {}.", opts.iter().map(|o| format!("`{o}`")).collect::<Vec<_>>().join(", ")),
                    config::Kind::Str => String::new(),
                };
                println!("| `{}` | {} | {} | **{}.** {}{kind} |", config::env_name(d.key), default(d.default), if d.restart { "after restart" } else { "at once" }, d.label, d.help.replace('|', "\\|"));
            }
        }
    }
    std::process::exit(0);
}

#[tokio::main]
async fn main() {
    match std::env::args().nth(1).as_deref() {
        Some("healthcheck") => healthcheck(),
        Some("env") => print_env(std::env::args().nth(2).as_deref()),
        _ => {}
    }

    let boot = config::Boot::from_env().unwrap_or_else(|e| fail(e));
    let settings = config::Settings::from_env().unwrap_or_else(|e| fail(e));

    let filter = tracing_subscriber::EnvFilter::try_new(format!("{},sqlx=warn", boot.log_level)).unwrap_or_else(|_| fail("SS_LOG_LEVEL is not valid"));
    if boot.log_format == "json" {
        tracing_subscriber::fmt().with_env_filter(filter).json().init();
    } else {
        tracing_subscriber::fmt().with_env_filter(filter).init();
    }

    let pool = db::connect(&boot).await.unwrap_or_else(|e| fail(e));
    db::migrate(&pool).await.unwrap_or_else(|e| fail(format!("database migration failed: {e}")));
    db::seed(&pool).await.unwrap_or_else(|e| fail(format!("database seed failed: {e}")));
    settings.load_db(db::load_settings(&pool).await.unwrap_or_else(|e| fail(e)));

    let listen = boot.listen;
    let (capture, rows) = ingest::new();
    let engine = local::Engine::new(boot.local_engine.clone(), &boot.data_dir, boot.local_port);
    let app = Arc::new(api::App {
        boot,
        settings,
        db: pool,
        storage: RwLock::new(None),
        storage_starting: AtomicBool::new(false),
        storage_generation: AtomicU64::new(0),
        local: engine,
        ingest: capture,
        live_sessions: AtomicUsize::new(0),
    });
    storage::refresh(&app).await.unwrap_or_else(|e| fail(e));
    auth::bootstrap_admin(&app).await.unwrap_or_else(|e| fail(e));
    ingest::load_sources(&app).await.unwrap_or_else(|e| fail(e));
    let watcher = app.clone();
    tokio::spawn(async move { watcher.local.watch().await });
    ingest::start(app.clone(), rows).await.unwrap_or_else(|e| fail(e));
    tokio::spawn(finalizer::run(app.clone()));

    // Picks up settings changed by another instance, and removes expired rows.
    let housekeeping = app.clone();
    tokio::spawn(async move {
        let mut tick = tokio::time::interval(Duration::from_secs(30));
        let mut runs = 0u64;
        loop {
            tick.tick().await;
            if let Ok(values) = db::load_settings(&housekeeping.db).await {
                housekeeping.settings.load_db(values);
            }
            if runs % 120 == 0 {
                let now = db::utc_now();
                let _ = sqlx::query("DELETE FROM sessions WHERE expires_at < ?").bind(now).execute(&housekeeping.db).await;
                let cutoff = now - chrono::Duration::days(housekeeping.settings.int("audit_retention_days"));
                let _ = sqlx::query("DELETE FROM audit_events WHERE ts < ?").bind(cutoff).execute(&housekeeping.db).await;
            }
            runs += 1;
        }
    });

    let listener = tokio::net::TcpListener::bind(listen).await.unwrap_or_else(|e| fail(format!("can't listen on {listen}: {e}")));
    tracing::info!("serving http://{listen}");
    let shutdown = async {
        let mut term = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate()).expect("signal handler");
        tokio::select! {
            _ = tokio::signal::ctrl_c() => {},
            _ = term.recv() => {},
        }
    };
    axum::serve(listener, api::router(app.clone()).into_make_service_with_connect_info::<SocketAddr>())
        .with_graceful_shutdown(shutdown)
        .await
        .unwrap_or_else(|e| fail(e));
    app.local.stop().await;
}
